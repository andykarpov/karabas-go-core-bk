#!/usr/bin/env python3
"""Generates rtl/bk/bk_kbd_rom.v: the key tables of retro-tang-bk mnano/bk.c (plain and shifted code
of a key in ЛАТ mode, bit 7 = АР2 implied, F0.. actions), indexed here by the PS/2 set 2 scancode
of kg_mcu ({shift, E0 prefix, code}) instead of the USB code.

usage: gen_kbd.py > rtl/bk/bk_kbd_rom.v
"""
N, STOP, RST, CAPS = 0x00, 0xF0, 0xF1, 0xF2
AR2 = 0x80
# (set 2 code with 0x100 for E0, plain, shifted)
def a(c): return ord(c)
keys = []
for ch, sc in zip('abcdefghijklmnopqrstuvwxyz',
                  [0x1C,0x32,0x21,0x23,0x24,0x2B,0x34,0x33,0x43,0x3B,0x42,0x4B,0x3A,
                   0x31,0x44,0x4D,0x15,0x2D,0x1B,0x2C,0x3C,0x2A,0x1D,0x22,0x35,0x1A]):
    keys.append((sc, a(ch), a(ch.upper())))
for ch, sh, sc in zip('1234567890', '!@#$%^&*()', [0x16,0x1E,0x26,0x25,0x2E,0x36,0x3D,0x3E,0x46,0x45]):
    keys.append((sc, a(ch), a(sh)))
keys += [
    (0x5A, 0o12, 0o15),   # Enter ВВОД, Shift УСТ ТАБ
    (0x76, 0o03, 0o03),   # Esc КТ
    (0x66, 0o30, 0o30),   # Backspace ЗАБОЙ
    (0x0D, 0o11, 0o20),   # Tab ТАБ, Shift СБР ТАБ
    (0x29, a(' '), a(' ')),
    (0x4E, a('-'), a('_')), (0x55, a('='), a('+')), (0x54, a('['), a('{')), (0x5B, a(']'), a('}')),
    (0x5D, a('\\'), a('|')), (0x4C, a(';'), a(':')), (0x52, a("'"), a('"')), (0x0E, a('`'), a('~')),
    (0x41, a(','), a('<')), (0x49, a('.'), a('>')), (0x4A, a('/'), a('?')),
    (0x58, CAPS, CAPS),   # СТР
    (0x05, AR2|0o01, AR2|0o01),  # F1 ПОВТ
    (0x06, 0o23, 0o23),          # F2 ВС
    (0x04, AR2|0o25, AR2|0o25),  # F3 ГРАФ
    (0x03, AR2|0o31, AR2|0o31),  # F5 -!->
    (0x0B, AR2|0o02, AR2|0o02),  # F6 ИНД СУ
    (0x83, AR2|0o04, AR2|0o04),  # F7 БЛОК РЕД
    (0x0A, AR2|0o20, AR2|0o20),  # F8 ШАГ
    (0x01, 0o14, 0o14),          # F9 СБР (clear)
    (0x09, STOP, STOP),          # F10 СТОП
    (0x78, RST, RST),            # F11 the reset key
    (0x170, 0o27, 0o27),  # Insert |-->
    (0x16C, 0o34, 0o34),  # Home up-left
    (0x17D, 0o35, 0o35),  # PageUp up-right
    (0x171, 0o26, 0o26),  # Delete |<--
    (0x169, 0o37, 0o37),  # End down-left
    (0x17A, 0o36, 0o36),  # PageDown down-right
    (0x174, 0o31, 0o31),  # right
    (0x16B, 0o10, 0o10),  # left
    (0x172, 0o33, 0o33),  # down
    (0x175, 0o32, 0o32),  # up
    (0x14A, a('/'), a('/')), (0x7C, a('*'), a('*')), (0x7B, a('-'), a('-')), (0x79, a('+'), a('+')),
    (0x15A, 0o12, 0o12),  # KP Enter
]
for ch, sc in zip('1234567890.', [0x69,0x72,0x7A,0x6B,0x73,0x74,0x6C,0x75,0x7D,0x70,0x71]):
    keys.append((sc, a(ch), a(ch)))

print("""`timescale 1ns / 1ps
// GENERATED by tools/gen_kbd.py from the tables of retro-tang-bk mnano/bk.c - do not edit.
// {shift, E0 prefix, set 2 code} -> the code of the key in ЛАТ mode: bit 7 = АР2 implied, F0 СТОП,
// F1 the reset key, F2 СТР, 0 no key.
module bk_kbd_rom (
    input            clk,
    input      [9:0] a,
    output reg [7:0] q = 8'd0
);
always @(posedge clk) case (a)""")
for sc, pl, sh in keys:
    print("    10'h%03x: q <= 8'h%02x;" % (sc, pl))
    print("    10'h%03x: q <= 8'h%02x;" % (sc | 0x200, sh))
print("""    default: q <= 8'h00;
endcase
endmodule""")
